import { esc, html } from './ui.js';

/**
 * Что в приложении честно не готово.
 *
 * ОДИН СПИСОК НА ВСЁ ПРИЛОЖЕНИЕ. Метку вешают в нескольких местах —
 * на плитку, в форму, — а снимают один раз, когда функция выходит.
 * Россыпь меток по экранам однажды означала бы «В разработке» на готовой
 * функции: выкатили в одном месте, забыли в двух других. Удаление строки
 * отсюда снимает метку везде сразу.
 *
 * Список не приходит с сервера намеренно: это три строки текста, ради
 * которых не стоит заводить поле в /api/me. Метка снимается тогда же,
 * когда выкладывается сама функция, — то есть выкладкой public/.
 */
export const WIP = {
  postPhoto: {
    badge: 'В разработке',
    note: 'Фотография сохранится вместе с объявлением, но в ленте её пока не видно.',
  },
  /**
   * ЗАГЛУШКА MVP: ЖК в подборе дома (docs/mock-complexes.md).
   * Снять — удалить строку, когда заглушку уберут (`mock:clear`).
   */
  /**
   * Удаление своих данных из приложения одной кнопкой (152-ФЗ, ст. 21).
   * Снять — когда появится удаление аккаунта целиком.
   */
  dataDelete: {
    badge: 'В разработке',
    note: 'Удалить аккаунт целиком из приложения пока нельзя.',
  },
  /**
   * ДЕМО-ДОМ для экспертов.
   * Снять — удалить строку, когда демо-дом уберут (`demo:clear`).
   */
  demoHouse: {
    badge: 'Демо-дом',
    note: 'Дом выдуманный: жители, заявки и начисления в нём — для проверки приложения.',
  },
  pickMock: {
    badge: 'Примерные данные',
    note: 'Сведения о ЖК собраны для показа: цены, отзывы и описание придуманы.',
  },
};

/** Метка на элементе: плитка, строка списка, заголовок раздела. */
export function wipBadge(key) {
  const entry = WIP[key];
  if (!entry) return '';
  return html`<span class="wip">${esc(entry.badge)}</span>`;
}

/**
 * Строка-пояснение внутри экрана: чего ждать от функции сегодня.
 *
 * Метка повторяется здесь не для красоты: человек пришёл сюда с плитки,
 * на которой она стояла, и по ней узнаёт, что этот серый блок — про то же
 * самое. Без неё две серые плашки подряд (пояснение и адресат обращения)
 * читаются как один текст из двух абзацев.
 */
export function wipNote(key) {
  const entry = WIP[key];
  if (!entry?.note) return '';
  return html`
    <div class="wip-note">
      <span class="wip">${esc(entry.badge)}</span>
      ${esc(entry.note)}
    </div>`;
}

/**
 * Что этот запуск разрешает.
 *
 * Одно место вместо разбросанных проверок `process.env.DEV_TOOLS === '1'`:
 * они управляли только разметкой, и из-за этого флаг выглядел защитой,
 * которой не был.
 */

/**
 * Читаем окружение в момент вызова, а не при импорте.
 *
 * Константа на уровне модуля вычисляется один раз за процесс, и тест
 * не может проверить боевое поведение, не поднимая второй процесс, —
 * то есть самое важное поведение остаётся непроверенным. Стоимость
 * обращения к process.env на запрос пренебрежима.
 */
export function isProduction(): boolean {
  return process.env.NODE_ENV === 'production';
}

/**
 * Вход жителя по QR из браузера.
 *
 * В БОЮ ЕГО НЕТ. Причина не в удобстве, а в том, что доказать нечем:
 * строка платёжного QR приходит обычным HTTP-запросом, и сервер не может
 * отличить код, снятый камерой с бумажной квитанции, от набранного руками.
 * Подписи в ГОСТ Р 56042-2014 не предусмотрено. Значит любой, кто угадал
 * номер лицевого счёта, входил бы как житель — что и было показано
 * на живом стенде.
 *
 * В бою человек приходит из MAX: там личность подтверждена подписью
 * платформы, а телефон — через requestContact. Браузерный путь остаётся
 * только для локальной разработки и автотестов, где базой всё равно
 * распоряжается разработчик.
 *
 * Кабинеты диспетчера и председателя это НЕ затрагивает — они браузерные
 * по замыслу и защищены паролем.
 */
/**
 * Секрет подписи: куки и короткие ссылки (QR квитанции для оплаты).
 * В бою обязателен — без него app.ts не поднимается.
 */
export function signingSecret(): string {
  return process.env.COOKIE_SECRET ?? 'dev-secret-change-me';
}

export function webLoginEnabled(): boolean {
  if (isProduction()) return false;
  return process.env.DEV_TOOLS !== '0';
}

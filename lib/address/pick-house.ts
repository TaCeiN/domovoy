/**
 * Выбор дома, когда реестр даёт несколько кандидатов.
 *
 * Один и тот же дом записывают по-разному: «Ленина 85/3» и «Ленина 85,
 * к. 3». Дробь корпусом мы намеренно не считаем — на пересечении улиц
 * дробью нумеруют самостоятельные дома, — поэтому ключи получаются разные,
 * и поиск идёт по нескольким вариантам сразу. Иногда находятся оба, и
 * тогда `limit 1` без сортировки выбирал строку наугад: житель реального
 * дома получал демонстрационную организацию.
 */

export interface HouseCandidate {
  houseKey: string;
  /** Пусто у дома без управления: частного, или когда реестр организацию не назвал */
  orgId: string | null;
  /** Статус организации в ГИС ЖКХ: REGISTERED, BLOCKED и прочие */
  gisStatus: string | null;
}

/**
 * Правила, по порядку:
 *
 * 1. Написание, которое житель указал сам. Он смотрит на свою квитанцию
 *    или на табличку у подъезда — это точнее любой эвристики.
 * 2. Действующая организация. Заблокированная дом за собой не держит:
 *    управление могло уже перейти другой компании.
 * 3. Дом, у которого организация вообще есть: дом без управления рядом
 *    с домом ТСЖ — скорее устаревшая запись, чем другое здание.
 * 4. Первый попавшийся — кандидат всё равно один.
 */
export function pickHouse<T extends HouseCandidate>(
  candidates: T[],
  exactKey: string | null,
): T | null {
  if (candidates.length === 0) return null;

  if (exactKey) {
    const exact = candidates.find((row) => row.houseKey === exactKey);
    if (exact) return exact;
  }

  return candidates.find((row) => row.orgId && row.gisStatus === 'REGISTERED')
    ?? candidates.find((row) => row.orgId)
    ?? candidates[0];
}

/**
 * Адрес дома из реестра плюс своя квартира.
 *
 * Один дом источники пишут по-разному: квитанция печатает «д. 85, к. 3»,
 * реестр ГИС ЖКХ — «д. 85/3». Ключ мы уже берём из реестра, иначе соседи
 * разошлись бы по разным домам. Но пока текст оставался квитанционным,
 * житель видел «Ленина 85к3», а его управляющая компания в своём кабинете
 * «Ленина 85/3»: один дом двумя строками.
 *
 * Реестр — общий источник правды об адресе, поэтому дом пишется его
 * словами. Квартира остаётся жительская: в реестре её нет и быть не может.
 */
export function addressWithFlat(registryAddress: string, flat: string | null): string {
  const house = registryAddress.trim().replace(/,\s*$/, '');
  return flat ? `${house}, кв. ${flat}` : house;
}

const BY_NAME = new Map(NAMES.map(([name, code]) => [key(name), code]));

/**
 * Города федерального значения.
 *
 * У них региона в адресе нет вовсе: реестр пишет «111677, г Москва,
 * ул Липчанского, д. 2», и разбор кладёт Москву в город, а не в регион.
 */
const FEDERAL_CITIES = new Map([
  ['москва', '77'],
  ['санкт-петербург', '78'],
  ['севастополь', '92'],
]);

/**
 * Код субъекта или `null`, если по адресу его не определить.
 *
 * `null` возвращается честно: реестр пишет и «346780, г Азов, ул Мира»,
 * и «…, р-н Аксайский, …» — без региона вообще. Подставить туда регион
 * импорта это решение вызывающего, а не разбора.
 */
export function regionCodeFromAddress(
  parsed: Pick<ParsedAddress, 'region' | 'city'>,
): string | null {
  if (parsed.region) {
    const found = BY_NAME.get(key(parsed.region));
    if (found) return found;
  }

  if (parsed.city) {
    const found = FEDERAL_CITIES.get(parsed.city.toLowerCase().replace(/ё/g, 'е'));
    if (found) return found;
  }

  return null;
}

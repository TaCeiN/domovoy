/**
 * Код субъекта РФ по разобранному адресу.
 *
 * Нужен потому, что ГИС ЖКХ отдаёт ВСЕ дома организации, не фильтруя их
 * по региону: компания с ростовской лицензией управляет домами в Балашихе.
 * Пока код региона брался из аргумента импорта, такие дома помечались
 * Ростовской областью — на 14 275 загруженных домов чужих оказалось 2091.
 *
 * Сопоставление идёт по НАЗВАНИЮ БЕЗ ТИПА. Иначе пришлось бы угадывать
 * точную строку канона для каждого из 85 субъектов: реестр пишет
 * «обл Ростовская», квитанция «Ростовская обл», а ХМАО после канонизации
 * выглядит как «ханты-мансийский - югра автономный округ».
 */
import type { ParsedAddress } from './normalize.ts';

/** Слова типа субъекта: в ключ не входят. */
const TYPE_WORDS = new Set([
  'область', 'обл', 'край', 'края', 'республика', 'респ',
  'ао', 'округ', 'автономный', 'автономная', 'автономного',
]);

/**
 * Ключ для сравнения: без типа, без знаков препинания, без «ё».
 *
 * Дефис и скобки стираются намеренно — «Северная Осетия - Алания»
 * и «Ханты-Мансийский АО — Югра» в источниках пишутся и через дефис,
 * и через тире, и без него вовсе.
 */
function key(name: string): string {
  return name
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^а-я0-9]+/g, ' ')
    .split(' ')
    .filter((word) => word && !TYPE_WORDS.has(word))
    .join(' ');
}


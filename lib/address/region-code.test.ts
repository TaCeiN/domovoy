import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseAddress } from './normalize.ts';
import { regionCodeFromAddress } from './region-code.ts';

/** Код субъекта по адресу-строке — как он приходит из реестра ГИС ЖКХ. */
const code = (address: string) => regionCodeFromAddress(parseAddress(address));

test('порядок слов не важен: реестр и квитанция дают один код', () => {
  assert.equal(code('346780, обл Ростовская, г Азов, ул Мира, д. 1'), '61');
  assert.equal(code('346780, Ростовская обл, г Азов, ул Мира, д. 1'), '61');
  assert.equal(code('346780, Ростовская область, г Азов, ул Мира, д. 1'), '61');
});

test('чужой регион в импорте Ростовской области получает СВОЙ код', () => {
  // ООО «Пик-комфорт» лицензирована в 61, дом стоит в Балашихе
  assert.equal(code('143908, обл Московская, г Балашиха, ул Реутовская, д. 5'), '50');
  assert.equal(code('172715, обл Тверская, р-н Фировский, пгт Великооктябрьский, ул Кооперативная, д. 7'), '69');
});

test('край и республика', () => {
  assert.equal(code('353924, край Краснодарский, г Новороссийск, ул Южная, д. 13'), '23');
  assert.equal(code('614000, край Пермский, г Пермь, ул Ленина, д. 1'), '59');
  assert.equal(code('420000, Респ Татарстан, г Казань, ул Баумана, д. 1'), '16');
});

test('города федерального значения: региона в адресе нет вовсе', () => {
  assert.equal(code('111677, г Москва, ул Липчанского, д. 2'), '77');
  assert.equal(code('190000, г Санкт-Петербург, ул Садовая, д. 5'), '78');
  assert.equal(code('299000, г Севастополь, ул Ленина, д. 1'), '92');
});

test('автономный округ с дефисом в названии', () => {
  assert.equal(code('628400, Ханты-Мансийский Автономный округ - Югра, г Сургут, ул Мира, д. 3'), '86');
});

test('регион в адресе не указан — кода нет, врать нельзя', () => {
  // Реестр пишет и так: «346780, г Азов, ул Мира, д. 1»
  assert.equal(code('346780, г Азов, ул Мира, д. 1'), null);
  assert.equal(code('346720, р-н Аксайский, п Рассвет, ул Институтская, д. 10'), null);
});

test('область-тёзка города не путается с городом федерального значения', () => {
  assert.equal(code('143000, обл Московская, г Одинцово, ул Мира, д. 1'), '50');
});

import type { GarHouse, GarObject } from './gar.ts';

/**
 * Адрес дома словами — из цепочки объектов ГАР.
 *
 * ЗАЧЕМ ИМЕННО ТАКОЕ НАПИСАНИЕ. Дома реестра всегда лежали у нас в том
 * виде, в каком их отдаёт ГИС ЖКХ: «обл Ростовская, р-н Аксайский,
 * г Аксай, ул Объездная, д. 7, к. 1». От этой строки посчитаны ключи уже
 * привязанных квартир, председателей и объявлений. Собери мы адрес
 * по-другому — и тот же дом получил бы новый ключ, а соседи разъехались бы.
 *
 * ПОЧЕМУ СБОРКА, А НЕ ТЕКСТ. У ГАР каждый уровень — отдельное поле с типом.
 * Ошибиться в разборе «ст-ца Старочеркасская, ул Советская» здесь негде:
 * разбирать нечего. Неточность остаётся только на стороне квитанции.
 */

/**
 * Уровни административного деления, которые попадают в адрес.
 *
 * 1 субъект, 2 район, 5 город, 6 населённый пункт, 7 планировочная
 * структура (СНТ, микрорайон), 8 улица. Уровни 3 и 4 — муниципальные
 * (м.р-н, г.п.): ГИС ЖКХ и квитанции их не печатают.
 */
const ADDRESS_LEVELS = new Set([1, 2, 5, 6, 7, 8]);

/** Дополнительный номер дома: справочник ADDHOUSE_TYPES */
const ADD_TYPE: Record<number, string> = { 1: 'к.', 2: 'стр.', 3: 'соор.', 4: 'литера' };

/**
 * «г.» → «г», «ул.» → «ул», но «тер. СНТ» остаётся как есть.
 *
 * С 2026 года ГАР пишет сокращения с точкой, а ГИС ЖКХ — без. Точку внутри
 * типа трогать нельзя: «тер СНТ» и «тер. СНТ» портал пишет по-разному.
 */
function typeWithoutDot(type: string): string {
  return type.trim().replace(/\.$/, '');
}

export function garHouseAddress(chain: GarObject[], house: GarHouse): string {
  const parts: string[] = [];

  for (const object of chain) {
    if (!ADDRESS_LEVELS.has(object.level)) continue;
    parts.push(`${typeWithoutDot(object.type)} ${object.name}`);
  }

  /**
   * Номер дома — всегда «д.».
   *
   * В ГАР бывают «владение» и «домовладение», но квитанции печатают «д.»,
   * а ключ дома тип номера не различает. Писать «двлд. 32» значило бы
   * показать жителю слово, которого нет на его квитанции.
   */
  let number = `д. ${house.num}`;
  if (house.add1 && house.addType1) number += `, ${ADD_TYPE[house.addType1] ?? 'к.'} ${house.add1}`;
  if (house.add2 && house.addType2) number += `, ${ADD_TYPE[house.addType2] ?? 'стр.'} ${house.add2}`;
  parts.push(number);

  return parts.join(', ');
}

import { and, eq, ne } from 'drizzle-orm';
import { property, userProperty } from '../../db/schema.ts';
import { houseState, type HouseForm } from '../house/form.ts';
import type { Database } from '../../db/client.ts';

/**
 * Формы, которые бывают только у многоквартирного дома.
 *
 * Все четыре описывают СПОСОБ УПРАВЛЕНИЯ ОБЩИМ ИМУЩЕСТВОМ: лицензированная
 * УК, товарищество собственников, кооператив, непосредственное управление
 * самими собственниками. У частного дома общего имущества нет — ни подъезда,
 * ни крыши на всех, ни земли под домом в долях, — значит управлять нечем
 * и ни одна из этих форм на нём стоять не может.
 *
 * 'none' и 'unknown' сюда не входят намеренно: первое значит «управления
 * нет ни в каком виде», второе — «никто ещё не сказал», и оба верны
 * для частного дома. 'private' тем более.
 */
const MULTI_FLAT_FORMS = new Set<HouseForm>(['uk', 'tsj', 'zhsk', 'direct']);

/**
 * Можно ли впустить человека хозяином частного дома сразу.
 *
 * ЗАЧЕМ ПРАВИЛО ВООБЩЕ. В частном доме подтверждать некому: УК нет,
 * председателя нет, соседей нет. Уровень 1 там пуст по определению —
 * дом и квартира это один объект. Значит подтверждение не открывает
 * ничего, кроме права звать домочадцев и отзывать у них доступ.
 *
 * ЗАЧЕМ ЗАЩИТА. `flat = ''` НЕ означает «частный дом». Он означает
 * «квартира неизвестна»: по ГОСТ Р 56042-2014 поле необязательное,
 * и расчётные центры его часто не печатают. Без проверок ниже житель
 * МКД со слепой квитанцией объявил бы себя хозяином объекта,
 * представляющего весь дом.
 *
 * Слово человека — только пятое условие. Первые четыре — данные.
 */
export async function canOwnPrivateHouse(
  db: Database,
  input: { houseKey: string; flat: string; declaredPrivate: boolean },
): Promise<boolean> {
  // 5. Человек сам говорит, что живёт в квартире — спорить не о чем
  if (!input.declaredPrivate) return false;

  // 1. У объекта есть номер квартиры
  if (input.flat !== '') return false;

  // 2. Дом в реестре лицензий: лицензия по ст. 192 ЖК РФ — только на МКД
  const state = await houseState(db, input.houseKey);
  if (state.multiFlat === true) return false;

  /**
   * 2а. Дому уже назначена форма управления общим имуществом.
   *
   * Реестр лицензий (условие выше) знает ТОЛЬКО дома под лицензированными
   * УК: ТСЖ, ЖСК и непосредственного управления там нет по определению —
   * см. комментарий к таблице `house` в db/schema.ts. Поэтому для МКД,
   * который оператор завёл как 'tsj', условие 2 молчит, а вместе с ним
   * молчат 3 и 4 (соседи ещё не сканировали квитанции) — и от захвата дома
   * остаётся одно слово человека: сказал «частный дом» и стал хозяином
   * объекта, представляющего дом целиком.
   *
   * Дом, о котором не знает вообще никто, это не закрывает: различить его
   * нечем, и это принятое ограничение. Закрывает дом, о котором знает
   * хоть кто-то.
   */
  if (MULTI_FLAT_FORMS.has(state.form)) return false;

  // 3. У дома уже есть объект с номером квартиры
  const [withFlat] = await db
    .select({ id: property.id })
    .from(property)
    .where(and(eq(property.houseKey, input.houseKey), ne(property.flat, '')))
    .limit(1);
  if (withFlat) return false;

  // 4. В доме уже есть хоть один житель
  const [someone] = await db
    .select({ id: userProperty.id })
    .from(userProperty)
    .innerJoin(property, eq(userProperty.propertyId, property.id))
    .where(eq(property.houseKey, input.houseKey))
    .limit(1);
  if (someone) return false;

  return true;
}

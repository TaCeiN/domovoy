/**
 * Кодирование строки в windows-1251.
 *
 * ЗАЧЕМ. По ГОСТ Р 56042-2014 признак кодировки стоит прямо в заголовке:
 * «1» — windows-1251, «2» — UTF-8, «3» — KOI8-R. Живые квитанции
 * расчётных центров печатаются как ST00011, то есть в win-1251,
 * где кириллица занимает ОДИН байт.
 *
 * Генератор обязан уметь оба варианта. Иначе он выдавал бы только
 * UTF-8, а самый частый в природе случай — ST00011 — остался бы
 * непроверенным. Именно в нём и живёт открытый риск: нативный сканер
 * MAX отдаёт готовую строку, и если он декодирует её как UTF-8,
 * ФИО и адрес приедут мусором (см. аудит, находка Ф-7).
 *
 * В Node есть TextDecoder для win-1251, но НЕ TextEncoder: кодировать
 * умеет только в UTF-8. Отсюда своя таблица.
 */

/**
 * Верхняя половина таблицы, коды 0x80..0xFF.
 *
 * Нижняя половина совпадает с ASCII и в таблице не нужна.
 */
const HIGH_HALF =
  'ЂЃ‚ѓ„…†‡€‰Љ‹ЊЌЋЏ'
  + 'ђ‘’“”•–—™љ›њќћџ'
  + ' ЎўЈ¤Ґ¦§Ё©Є«¬­®Ї'
  + '°±Ііґµ¶·ё№є»јЅѕї'
  + 'АБВГДЕЖЗИЙКЛМНОП'
  + 'РСТУФХЦЧШЩЪЫЬЭЮЯ'
  + 'абвгдежзийклмноп'
  + 'рстуфхцчшщъыьэюя';

const TO_BYTE = new Map();
for (let i = 0; i < HIGH_HALF.length; i++) {
  TO_BYTE.set(HIGH_HALF[i], 0x80 + i);
}

/**
 * Строка в байты windows-1251.
 *
 * Символ, которого в кодировке нет, заменяется вопросительным знаком —
 * ровно так же поступает принтер квитанции. Молча ронять генерацию
 * из-за одного «ё» в чужой раскладке смысла нет.
 */
export function encodeCp1251(text) {
  const bytes = new Uint8Array(text.length);

  for (let i = 0; i < text.length; i++) {
    const code = text.codePointAt(i);
    if (code < 0x80) {
      bytes[i] = code;
      continue;
    }
    bytes[i] = TO_BYTE.get(text[i]) ?? 0x3f;
  }
  return bytes;
}

/** Строка в байты по признаку кодировки из заголовка ГОСТ. */
export function encodeByFlag(text, flag) {
  if (flag === '1') return encodeCp1251(text);
  if (flag === '2') return new TextEncoder().encode(text);
  throw new Error(`генератор умеет только кодировки 1 (win-1251) и 2 (UTF-8), получено «${flag}»`);
}

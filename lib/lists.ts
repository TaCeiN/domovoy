/** Сколько строк отдаём без просьбы и сколько добавляет «Показать ещё». */
export const LIST_PAGE = 50;

/**
 * Верхняя граница.
 *
 * `limit` приходит из адресной строки, и без потолка «Показать ещё»
 * однажды стало бы выгрузкой всей истории одним ответом.
 */
export const LIST_MAX = 500;

export function readLimit(value: unknown): number {
  /**
   * Пустая строка и `null` тоже дают ноль через `Number`, а это разные
   * случаи: «параметра нет» — это страница по умолчанию, а явный `0` —
   * попытка задать размер, и её достаточно поднять до единицы.
   */
  const given = typeof value === 'number' ? String(value) : (value ?? '');
  if (typeof given !== 'string' || given.trim() === '') return LIST_PAGE;

  const asked = Number(given);
  if (!Number.isFinite(asked)) return LIST_PAGE;
  return Math.min(LIST_MAX, Math.max(1, Math.floor(asked)));
}

/**
 * Совпадает ли строка запроса хотя бы с одним из полей.
 *
 * Регистр не важен: диспетчер набирает как придётся, а житель звонит
 * и называет «Ленина» или «лифт». Пустой запрос — это отсутствие поиска,
 * а не «ничего не найдено».
 */
export function matchesQuery(fields: (string | null | undefined)[], q: string): boolean {
  const needle = q.trim().toLowerCase();
  if (!needle) return true;
  return fields.some((field) => (field ?? '').toLowerCase().includes(needle));
}

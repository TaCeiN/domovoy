import { test } from 'node:test';
import assert from 'node:assert/strict';
import { quickIntent, outageTopic } from './quick.ts';

/**
 * Вопросы, которые маленькая модель путает с «общими»: номер скорой,
 * когда отключат воду. Ответ на них есть в данных — значит, отвечать
 * должен код, а не угадывание (жалоба владельца 29.09).
 */

test('номера экстренных служб — к телефонам, без модели', () => {
  for (const text of [
    'какой номер у скорой', 'Телефон полиции', 'как вызвать пожарных', 'куда звонить в мчс',
    'номер скорой помощи', 'скорую как вызвать с мобильного', 'телефон газовой службы', 'аварийка телефон',
  ]) assert.equal(quickIntent(text), 'contacts', text);
});

test('отключения — к объявлениям дома', () => {
  for (const text of [
    'когда отключение воды', 'будет ли отключение света', 'когда дадут горячую воду',
    'до скольки не будет воды', 'когда включат отопление', 'плановое отключение газа',
  ]) assert.equal(quickIntent(text), 'outage', text);
});

test('на остальное правила не срабатывают — решает модель', () => {
  for (const text of [
    'хочу отключить уведомления', 'нет горячей воды', 'сколько платить', 'лифт сломался',
    'привет', 'позвонил в скорую, а они не едут, в подъезде темно',
  ]) assert.equal(quickIntent(text), null, text);
});

test('о каком ресурсе речь — чтобы сверить жалобу с объявлением об отключении', () => {
  assert.equal(outageTopic('нет горячей воды третий день'), 'water');
  assert.equal(outageTopic('Отключение холодной воды'), 'water');
  assert.equal(outageTopic('в квартире нет света'), 'power');
  assert.equal(outageTopic('Плановое отключение электроэнергии'), 'power');
  assert.equal(outageTopic('батареи холодные'), 'heat');
  assert.equal(outageTopic('нет газа на плите'), 'gas');
  assert.equal(outageTopic('лифт не работает'), null);
});

test('живой человек и благодарность — тоже без модели', () => {
  for (const text of ['позови оператора', 'хочу поговорить с человеком', 'соедини с диспетчером'])
    assert.equal(quickIntent(text), 'contacts', text);
  for (const text of ['спасибо', 'Спасибо большое!', 'ок', 'понятно', 'благодарю'])
    assert.equal(quickIntent(text), 'thanks', text);
  assert.equal(quickIntent('спасибо, а когда дадут воду'), 'outage', 'вопрос важнее благодарности');
});

test('чужая квартира — отказ, своя — дальше по обычному пути', () => {
  for (const text of ['какой долг у кв. 15', 'сколько платит квартира 27', 'кто живёт в 27', 'кто живет в квартире 3', 'телефон собственника кв 40'])
    assert.equal(quickIntent(text, { flat: '12' }), 'foreign', text);
  assert.equal(quickIntent('какой долг у кв. 12', { flat: '12' }), null, 'своя квартира — не чужая');
  assert.equal(quickIntent('в кв 15 течёт потолок', { flat: '12' }), null, 'жалоба про соседа сверху — не вопрос о чужих данных');
});

test('вопросы о законах — честно: не консультирую', () => {
  for (const text of ['имеют право отключать воду на месяц?', 'это законно?', 'по какому закону повысили тариф', 'могут ли оштрафовать', 'что говорит жилищный кодекс'])
    assert.equal(quickIntent(text), 'law', text);
  assert.equal(quickIntent('когда отключение воды'), 'outage');
});

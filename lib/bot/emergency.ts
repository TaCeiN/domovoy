/**
 * Опасные ситуации в сообщении боту — без модели.
 *
 * Маленькая модель может не узнать «пахнет газом в подъезде» или принять
 * это за жалобу на запах. Здесь ошибка стоит слишком дорого, поэтому
 * такие сообщения ловит словарь, до обращения к GigaChat и до лимитов.
 * Ответ — только номера: 112, газ 104 и телефоны дома из «Аварийных
 * служб». Советов, что делать, бот не даёт — это не его данные.
 */

export type Danger = 'gas' | 'fire' | 'electric' | 'flood' | 'lift' | 'medical' | 'violence';

const RULES: Array<[Danger, RegExp]> = [
  ['gas', /(пахн|воня|запах|утечк|чу[вю]ств)\S*\s+(\S+\s+){0,3}газ|газ\S*\s+(\S+\s+){0,3}(пахн|воня|запах|утечк)|утечк\S* газ/],
  ['fire', /пожар|горит (квартир|подъезд|подвал|дом|щит|провод|мусор)|(^|[^а-я])дым|задымл/],
  ['electric', /искр|коротит|замыкани|(бь[её]т|ударил\S*) током|оголен\S* провод/],
  ['flood', /топят|затоп|залива|залило|прорвал|хлещет|льет?ся с потолка|потоп/],
  ['lift', /застрял\S*.{0,30}лифт|лифт.{0,30}застрял|в лифте.{0,20}(люди|человек|ребен)/],
  /**
   * Человеку плохо — скорая (29.09). Модель такое видела бы жалобой или
   * «общим вопросом», а ответ нужен сразу: номер, без советов.
   * «Плохо» — только про человека: «плохо убирают подъезд» не про это.
   */
  /**
   * Драка, ломятся в дверь, угрозы — полиция (29.09). Стоит после electric:
   * «бьёт током» — это электрика, а не нападение.
   */
  ['violence', /драк|дерутся|ломит?ся в дверь|ломятся|выламыва|угрожа|напал|избива|грабят|ограбил|воры|вор в |стреля|с ножом|ножом/],
  ['medical', /(человек\S*|ему|ей|мне|маме|папе|бабушке|дедушке|ребенку|соседу|соседке)\s+(стало\s+)?плохо|без сознания|потерял\S* сознани|не дышит|инфаркт|инсульт|сердечн\S* приступ|упал\S*\s+и\s+не\s+(встает|может встать|шевел)|кровь не останавл/],
];

export function detectDanger(text: string): Danger | null {
  const t = text.toLowerCase().replaceAll('ё', 'е');
  for (const [kind, re] of RULES) if (re.test(t)) return kind;
  return null;
}

export interface DangerContact {
  kind: string;
  title: string;
  phone: string;
}

/** Какие телефоны дома к какой беде: при газе лифтёрская не нужна. */
const HOUSE_KINDS: Record<Danger, string[]> = {
  gas: ['uk_dispatch'],
  fire: ['uk_dispatch'],
  electric: ['electric', 'uk_dispatch'],
  flood: ['plumber', 'uk_dispatch'],
  lift: ['lift', 'uk_dispatch'],
  medical: [],
  violence: [],
};

export function dangerReply(kind: Danger, contacts: DangerContact[]): string {
  const lines = ['Если есть угроза жизни или здоровью — сразу звоните 112.'];
  if (kind === 'gas') lines.push('Запах газа — аварийная газовая служба: 104.');
  if (kind === 'fire') lines.push('Пожарная охрана: 101.');
  if (kind === 'medical') lines.push('Скорая помощь: 103 (с мобильного тоже).');
  if (kind === 'violence') lines.push('Полиция: 102 (с мобильного тоже).');

  const own = contacts.filter((c) => HOUSE_KINDS[kind].includes(c.kind));
  if (own.length) {
    lines.push('', 'Телефоны вашего дома:');
    for (const c of own) lines.push(`${c.title}: ${c.phone}`);
  }
  return lines.join('\n');
}

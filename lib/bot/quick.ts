/**
 * Вопросы, на которые отвечает код, а не модель.
 *
 * Маленькая модель уводила «какой номер у скорой» и «когда отключение
 * воды» в «общие вопросы» (жалоба владельца 29.09), хотя ответ на оба
 * лежит в данных: номера служб — в каталоге, отключения — в объявлениях
 * дома. Здесь ошибка дорогая, а вопросы узнаются по словам — как
 * опасные ситуации в emergency.ts. Заодно они работают и без ключа
 * GigaChat, и сверх дневного лимита модели.
 *
 * Правила узкие нарочно: не сработали — сообщение разбирает модель,
 * как раньше. Жалобу («нет горячей воды») сюда не забираем — у неё свой
 * путь с черновиком.
 */

export type QuickIntent = 'contacts' | 'outage' | 'thanks' | 'foreign' | 'law';

const norm = (text: string) => text.toLowerCase().replaceAll('ё', 'е');

/** Экстренные и аварийные службы — по названию или номеру */
const SERVICE = /скор|полиц|пожарн|мчс|газов\S*\s+служб|аварийк|аварийн\S*\s+служб|экстренн|(^|\D)(112|101|102|103|104)(\D|$)/;
/** Спрашивает, как связаться, — а не рассказывает, что уже звонил */
const HOW_TO_CALL = /номер|телефон|позвонить|звонить|вызвать|вызывать/;
const ALREADY_CALLED = /позвонил|вызвал|звонил|не едут|не приезжа/;

/** Отключения — но не «отключить уведомления» */
const OUTAGE_WORD = /отключ/;
const NOT_OUTAGE = /уведомл|оповещ|рассылк|звук|отключить/;
const RESOURCE = /вод|свет|электр|газ|отоплен|тепл/;
const WHEN_BACK = /(когда|во сколько|до скольки|надолго|сколько еще|будет ли|будут ли)\s.{0,30}(дадут|включат|вернут|подадут|появится|будет|не будет)/;

/** Хочет живого человека — отвечаем телефоном УК, как на «телефон диспетчерской» */
const HUMAN = /оператор|живо\S* человек|поговорить с человеком|соедини\S*|связаться с (диспетчер|ук)/;

/** Всё сообщение — благодарность или «ок»; вопрос после «спасибо» разбираем дальше */
const THANKS = /^(спасибо|спс|благодарю|ок|окей|ok|понятно|понял|поняла|ясно|хорошо)(\s+(большое|огромное|вам|тебе))?[\s!.)]*$/;

/**
 * Вопрос о чужой квартире: деньги, жильцы, их телефоны. Бот знает только
 * квартиры жителя — и отвечал бы суммами СВОЕЙ, будто про кв. 15 (29.09).
 * «В кв 15 течёт потолок» — жалоба, а не вопрос о данных: её не трогаем.
 */
const FLAT_NO = /(?:кв\.?|квартир\S*)\s*№?\s*(\d+[а-я]?)/;
const ABOUT_PEOPLE_OR_MONEY = /долг|должн|задолж|плат|начисл|квитанц|жив[еу]т|проживает|жильц|собственник|владел|фамили|телефон|номер|кто/;
const WHO_LIVES = /кто\s+(там\s+)?(жив[еу]т|проживает|прописан)/;

/**
 * Законы и права — к юристу: консультации отложены до юриста. Честно
 * говорим, что не консультируем, вместо общей справки о возможностях.
 */
const LAW = /закон|имеют ли право|имеют право|имеет право|вправе|законно|незаконно|юрист|в суд|штраф|жилищн\S* кодекс|жк рф|постановлени|статья|стать[ея] \d/;

export function quickIntent(text: string, own: { flat?: string | null } = {}): QuickIntent | null {
  const t = norm(text);
  const flat = FLAT_NO.exec(t)?.[1];
  const ownFlat = own.flat ? norm(own.flat) : null;
  if ((flat && flat !== ownFlat && ABOUT_PEOPLE_OR_MONEY.test(t)) || (WHO_LIVES.test(t) && flat !== ownFlat)) return 'foreign';
  if (LAW.test(t)) return 'law';
  if (SERVICE.test(t) && HOW_TO_CALL.test(t) && !ALREADY_CALLED.test(t)) return 'contacts';
  if (OUTAGE_WORD.test(t) && !NOT_OUTAGE.test(t)) return 'outage';
  if (WHEN_BACK.test(t) && RESOURCE.test(t)) return 'outage';
  if (HUMAN.test(t)) return 'contacts';
  if (THANKS.test(t.trim())) return 'thanks';
  return null;
}

export type OutageTopic = 'water' | 'power' | 'heat' | 'gas';

/**
 * О каком ресурсе речь — чтобы жалобу «нет горячей воды» сверить
 * с объявлением «Отключение горячей воды», а не с отключением света.
 */
export function outageTopic(text: string): OutageTopic | null {
  const t = norm(text);
  if (/вод|гвс|хвс|кипят/.test(t)) return 'water';
  if (/свет|электр/.test(t)) return 'power';
  if (/отоплен|батаре|тепл/.test(t)) return 'heat';
  if (/газ/.test(t)) return 'gas';
  return null;
}

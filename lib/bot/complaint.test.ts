import { test } from 'node:test';
import assert from 'node:assert/strict';
import { sameTopic } from './complaint.ts';

/**
 * Повтор жалобы — по смыслу, а не по категории.
 *
 * Владелец 28.09: на «Не вывозят мусор» бот предложил уже открытую заявку
 * про другое — у них совпала только категория «Общее имущество».
 */

test('одна и та же беда разными словами — повтор', () => {
  assert.ok(sameTopic('Лифт не работает третий день.', 'Не работает лифт'));
  assert.ok(sameTopic('Мусор не вывозят неделю. Прошу организовать вывоз.', 'Не вывозят мусор с площадки'));
  assert.ok(sameTopic('В квартире нет горячей воды', 'Нет горячей воды второй день'));
});

test('одна категория, но разные беды — не повтор', () => {
  assert.equal(sameTopic('Мусор не вывозят неделю. Прошу организовать вывоз.', 'Сломана дверь в подъезде'), false);
  assert.equal(sameTopic('Не работает домофон', 'Не работает лифт'), false, '«не работает» — общее слово, не тема');
  assert.equal(sameTopic('В подъезде грязно, не убирают', 'В подъезде перегорела лампочка'), false, '«подъезд» — место, не тема');
});

test('общие слова жалобы в сравнение не идут', () => {
  assert.equal(sameTopic('Прошу сообщить причину и срок восстановления', 'Прошу восстановить в срок'), false);
});
